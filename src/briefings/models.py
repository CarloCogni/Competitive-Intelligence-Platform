# briefings/models.py
"""
Models for the AI-powered weekly intelligence briefing.

WeeklyBriefing stores a single LLM-generated markdown report covering
a configurable time window of alerts, metrics, and news. One briefing
is generated per scheduled run; on-demand generation is also supported
via the dashboard.
"""

import logging

from django.db import models
from django.utils import timezone

logger = logging.getLogger(__name__)


class WeeklyBriefing(models.Model):
    """
    A single AI-generated competitive intelligence briefing.

    Generated by BriefingGenerator from the past N days of Alert, Metric,
    and NewsItem records. Content is stored as markdown and rendered in
    the dashboard. Status tracks async generation lifecycle.
    """

    class Status(models.TextChoices):
        PENDING = "pending", "Pending"
        GENERATING = "generating", "Generating"
        READY = "ready", "Ready"
        FAILED = "failed", "Failed"

    # The date window this briefing covers
    period_start = models.DateTimeField(help_text="Start of the data window fed to the LLM.")
    period_end = models.DateTimeField(
        default=timezone.now,
        help_text="End of the data window (typically 'now' at generation time).",
    )

    # LLM output
    content = models.TextField(blank=True, help_text="Markdown output from the LLM.")
    model_used = models.CharField(
        max_length=100,
        blank=True,
        help_text="Ollama model identifier used, e.g. 'llama3.1:8b'.",
    )

    # Generation lifecycle
    status = models.CharField(
        max_length=20,
        choices=Status.choices,
        default=Status.PENDING,
    )
    generated_at = models.DateTimeField(
        null=True,
        blank=True,
        help_text="When LLM generation completed successfully.",
    )
    error_message = models.TextField(blank=True, help_text="Error detail if status=failed.")

    # Metadata about the prompt context
    entity_count = models.IntegerField(
        default=0,
        help_text="Number of distinct entities referenced in the prompt.",
    )
    alert_count = models.IntegerField(
        default=0,
        help_text="Number of alerts fed into the prompt.",
    )
    news_count = models.IntegerField(
        default=0,
        help_text="Number of news headlines fed into the prompt.",
    )

    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = "Weekly Briefing"
        verbose_name_plural = "Weekly Briefings"
        ordering = ["-period_end"]
        indexes = [
            models.Index(fields=["status", "period_end"]),
        ]

    def __str__(self) -> str:
        return f"Briefing {self.period_end:%Y-%m-%d} [{self.get_status_display()}]"

    @property
    def is_in_progress(self) -> bool:
        """True while the briefing is being generated (pending or generating)."""
        return self.status in (self.Status.PENDING, self.Status.GENERATING)


class BriefingConfig(models.Model):
    """
    Singleton configuration for AI briefing generation.

    Only one row ever exists (pk=1, enforced in save()). Use BriefingConfig.get()
    to retrieve or create the singleton with defaults.
    """

    class LLMProvider(models.TextChoices):
        """Which LLM backend to use for briefing generation."""

        AUTO = "auto", "Auto (Ollama → Groq fallback)"
        OLLAMA = "ollama", "Ollama (local)"
        GROQ = "groq", "Groq (cloud)"

    # --- LLM provider ---
    llm_provider = models.CharField(
        max_length=10,
        choices=LLMProvider.choices,
        default=LLMProvider.AUTO,
        help_text="Which LLM backend to use. AUTO tries Ollama first, falls back to Groq.",
    )

    # --- Ollama settings ---
    ollama_model = models.CharField(
        max_length=100,
        default="gemma4:e4b",
        help_text=(
            "Ollama model identifier, e.g. 'gemma4:e4b'. Used when "
            "provider is Ollama or Auto."
        ),
    )

    # --- Groq settings ---
    groq_api_key = models.CharField(
        max_length=200,
        blank=True,
        help_text=(
            "Groq API key (https://console.groq.com/keys). Stored in DB; "
            "never committed to .env."
        ),
    )
    groq_model = models.CharField(
        max_length=100,
        default="llama-3.3-70b-versatile",
        help_text=(
            "Groq model identifier. Free-tier options: "
            "llama-3.3-70b-versatile, llama-3.1-8b-instant."
        ),
    )

    # --- Data window ---
    period_days = models.IntegerField(
        default=7,
        help_text="Number of days of data (alerts, news, metrics) to include in each briefing.",
    )

    # --- Email delivery ---
    send_briefing_email = models.BooleanField(
        default=False,
        help_text="Email the full briefing to recipients when generation completes.",
    )
    briefing_email_recipients = models.TextField(
        blank=True,
        help_text="Comma-separated email addresses to receive the full AI briefing.",
    )

    class Meta:
        verbose_name = "Briefing Configuration"
        verbose_name_plural = "Briefing Configuration"

    def __str__(self) -> str:
        return f"BriefingConfig (provider={self.llm_provider}, period={self.period_days}d)"

    def save(self, *args, **kwargs) -> None:
        """Enforce singleton: always write to pk=1."""
        self.pk = 1
        super().save(*args, **kwargs)

    @classmethod
    def get(cls) -> "BriefingConfig":
        """Return the singleton row, creating it with defaults if it does not exist."""
        obj, _ = cls.objects.get_or_create(pk=1)
        return obj


class EmailConfig(models.Model):
    """
    Singleton SMTP transport configuration.

    Decouples email credentials from .env so operators can update SMTP
    settings via the dashboard UI without a server restart. Only one row
    ever exists (pk=1). When smtp_host is blank, email delivery is skipped.
    """

    smtp_host = models.CharField(
        max_length=255,
        blank=True,
        help_text="SMTP server hostname, e.g. 'smtp.gmail.com'. Leave blank to disable.",
    )
    smtp_port = models.IntegerField(
        default=587,
        help_text="SMTP port. Typically 587 (STARTTLS) or 465 (SSL).",
    )
    smtp_user = models.CharField(
        max_length=255,
        blank=True,
        help_text="SMTP login username or email address.",
    )
    smtp_password = models.CharField(
        max_length=255,
        blank=True,
        help_text="SMTP login password or app-specific password.",
    )
    use_tls = models.BooleanField(
        default=True,
        help_text="Use STARTTLS. Disable only for SSL (port 465) or local relays.",
    )
    default_from_email = models.CharField(
        max_length=255,
        default="noreply@compintel.local",
        help_text="From address shown on outgoing emails.",
    )

    class Meta:
        verbose_name = "Email Configuration"
        verbose_name_plural = "Email Configuration"

    def __str__(self) -> str:
        return f"EmailConfig (host={self.smtp_host or 'not configured'})"

    def save(self, *args, **kwargs) -> None:
        """Enforce singleton: always write to pk=1."""
        self.pk = 1
        super().save(*args, **kwargs)

    @classmethod
    def get(cls) -> "EmailConfig":
        """Return the singleton row, creating it with defaults if it does not exist."""
        obj, _ = cls.objects.get_or_create(pk=1)
        return obj

    @property
    def is_configured(self) -> bool:
        """True when a valid SMTP host is set."""
        return bool(self.smtp_host)
